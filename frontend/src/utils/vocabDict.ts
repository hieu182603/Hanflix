/**
 * Enriches a vocabulary token or drill word with dictionary knowledge
 * if any fields are missing from backend database.
 */
export function enrichVocabItem(word: string, existing?: Partial<VocabEntry>): VocabEntry {
  const cleanWord = word.trim();
  const dictMatch = COMMON_VOCAB_DB[cleanWord];

  return {
    hanzi: cleanWord,
    pinyin: existing?.pinyin || dictMatch?.pinyin || '',
    hanViet: existing?.hanViet || dictMatch?.hanViet || '',
    meaningVi: existing?.meaningVi || dictMatch?.meaningVi || '',
    partOfSpeech: existing?.partOfSpeech || dictMatch?.partOfSpeech || 'Từ vựng',
    hsk: existing?.hsk || dictMatch?.hsk || 1,
    collocations: existing?.collocations || dictMatch?.collocations || [],
    examples: existing?.examples || dictMatch?.examples || [],
  };
}
