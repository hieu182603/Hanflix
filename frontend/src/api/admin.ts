export interface AdminLessonListParams {
  page?: number;
  limit?: number;
  hsk?: number;
  status?: AdminLessonStatus;
  search?: string;
  // CONTENT MODE: filter theo contentMode ở admin list.
  contentMode?: ContentMode;
}

export interface AdminLessonListResponse {
  items: AdminLesson[];
  pagination: { page: number; limit: number; total: number; totalPages: number };
}

export async function listAdminLessons(
  params: AdminLessonListParams = {},
): Promise<AdminLessonListResponse> {
  const searchParams = new URLSearchParams();
  if (params.page) searchParams.set('page', String(params.page));
  if (params.limit) searchParams.set('limit', String(params.limit));
  if (params.hsk !== undefined) searchParams.set('hsk', String(params.hsk));
  if (params.status) searchParams.set('status', params.status);
  if (params.search) searchParams.set('search', params.search);
  if (params.contentMode) searchParams.set('contentMode', params.contentMode);
  const qs = searchParams.toString();
  const data = await apiFetch<{ items: AdminLesson[]; pagination: AdminLessonListResponse['pagination'] }>(
    `/admin/lessons${qs ? `?${qs}` : ''}`,
  );
  return { items: data.items, pagination: data.pagination };
}

/** Complete collection for admin screens that filter and paginate locally. */
export async function listAllAdminLessons(): Promise<AdminLessonListResponse> {
  const first = await listAdminLessons({ page: 1, limit: 100 });
  const items = [...first.items];
  for (let page = 2; page <= first.pagination.totalPages; page++) {
    const next = await listAdminLessons({ page, limit: 100 });
    items.push(...next.items);
  }
  return { ...first, items };
}

